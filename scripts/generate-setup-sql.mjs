// Builds supabase/setup-all.sql: the migrations and the seed, in order, as one
// file to paste into the Supabase SQL Editor. Regenerate after changing any of
// them: npm run cms:setup-sql
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const parts = [
  'supabase/migrations/20261014000000_cms_mvp.sql',
  'supabase/migrations/20261020000000_cms_documents.sql',
  'supabase/seed.sql',
]

const sections = parts.map((path) => {
  const sql = readFileSync(new URL(path, root), 'utf8')
  if (/^\s*(begin|commit|rollback)\s*;/im.test(sql)) throw new Error(`${path} has its own transaction statements`)
  const hash = createHash('sha256').update(sql).digest('hex').slice(0, 12)
  return `-- ===========================================================================\n-- ${path} (sha256 ${hash})\n-- ===========================================================================\n\n${sql.trimEnd()}\n`
})

const output = `-- Life X Therapy CMS: complete database setup.
-- GENERATED by \`npm run cms:setup-sql\`. Do not edit; edit the files below instead.
--
-- Paste this whole file into Supabase → SQL Editor → New query and run it once.
-- It is safe to run again, on a fresh project or on one where the earlier MVP
-- was already applied: every statement is idempotent and the seed never
-- overwrites existing content. Afterwards run supabase/tests/rls_check.sql.
--
-- Contents, in order:
${parts.map((path, index) => `--   ${index + 1}. ${path}`).join('\n')}

${sections.join('\n')}`

writeFileSync(new URL('supabase/setup-all.sql', root), output)
console.log(`supabase/setup-all.sql: ${parts.length} files, ${output.split('\n').length} lines`)
