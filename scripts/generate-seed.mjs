// Generates supabase/seed.sql from src/lib/cms/defaults/site-content.json, so
// the database and the site's built-in content can never drift apart.
// Usage: npm run cms:seed
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const content = JSON.parse(readFileSync(new URL('src/lib/cms/defaults/site-content.json', root), 'utf8'))

const docs = [
  ['settings', 'site', content.settings],
  ...Object.entries(content.pages).map(([key, data]) => ['page', key, data]),
  ...content.services.map((service) => ['service', service.id, service.data]),
  ['faqs', 'all', content.faqs],
]

const literal = (value) => {
  const json = JSON.stringify(value)
  if (json.includes('$seed$')) throw new Error('content contains the dollar-quote tag')
  return `$seed$${json}$seed$::jsonb`
}

const rows = docs.map(([kind, key, data]) => `  ('${kind}', '${key}', ${literal(data)})`).join(',\n')

const sql = `-- Initial CMS content: exactly what the website showed before the CMS.
-- GENERATED by \`npm run cms:seed\` from src/lib/cms/defaults/site-content.json.
--
-- Safe to run more than once: documents that already exist are never
-- overwritten, so edits made in the dashboard are kept. If the earlier MVP
-- dashboard was used on this project, its home hero, contact details and
-- promotions are carried over instead of the defaults.

create temporary table cms_seed (kind text, key text, draft jsonb, published jsonb);

insert into cms_seed (kind, key, draft)
values
${rows};

update cms_seed set published = draft;

-- Carry over content edited with the MVP dashboard, if its tables exist.
do $carry$
declare
  v_hero jsonb;
  v_contact jsonb;
  v_state text;
begin
  if to_regclass('public.content_drafts') is null then
    return;
  end if;

  foreach v_state in array array['draft', 'published'] loop
    if v_state = 'draft' then
      select data into v_hero from public.content_drafts where key = 'home_hero';
      select data into v_contact from public.content_drafts where key = 'contact';
    else
      select data into v_hero from public.content_published where key = 'home_hero';
      select data into v_contact from public.content_published where key = 'contact';
    end if;

    if v_hero is not null then
      execute format(
        'update cms_seed set %I = jsonb_set(%I, ''{sections,0,data}'', $1) where kind = ''page'' and key = ''home''',
        v_state, v_state)
      using jsonb_build_object(
        'eyebrow', coalesce(v_hero ->> 'eyebrow', ''),
        'headline', coalesce(v_hero ->> 'headline', '') || case when coalesce(v_hero ->> 'headlineEmphasis', '') <> ''
                                                   then E'\\n*' || (v_hero ->> 'headlineEmphasis') || '*' else '' end,
        'body', coalesce(v_hero ->> 'body', ''),
        'image', jsonb_build_object('src', coalesce(v_hero ->> 'image', '/images/hero-massage.jpg'), 'alt', coalesce(v_hero ->> 'imageAlt', '')),
        'primaryLabel', coalesce(v_hero ->> 'primaryLabel', 'Book a Session'),
        'secondary', jsonb_build_object('label', coalesce(v_hero ->> 'secondaryLabel', 'Explore Services'), 'href', coalesce(v_hero ->> 'secondaryHref', '/services'), 'ariaLabel', ''));
    end if;

    if v_contact is not null then
      execute format(
        'update cms_seed set %I = %I || $1 where kind = ''settings'' and key = ''site''',
        v_state, v_state)
      using jsonb_build_object(
        'contact', jsonb_build_object('phone', coalesce(v_contact ->> 'phone', ''), 'email', coalesce(v_contact ->> 'email', ''), 'address', coalesce(v_contact ->> 'address', '')),
        'hours', coalesce(v_contact -> 'hours', '[]'::jsonb),
        'social', jsonb_build_object('instagramUrl', coalesce(v_contact ->> 'instagramUrl', ''), 'facebookUrl', coalesce(v_contact ->> 'facebookUrl', '')));
    end if;
  end loop;

  insert into cms_seed (kind, key, draft, published)
  select 'promotion', d.id::text,
         jsonb_build_object(
           'title', d.title, 'description', d.description,
           'image', jsonb_build_object('src', coalesce(d.image_path, ''), 'alt', d.image_alt),
           'link', jsonb_build_object('label', case when d.link_url is null then '' when d.link_label = '' then 'Learn More' else d.link_label end,
                                      'href', coalesce(d.link_url, ''), 'ariaLabel', ''),
           'placements', '["home"]'::jsonb, 'startsAt', '', 'endsAt', '', 'sortOrder', d.sort_order),
         case when p.id is null then null else jsonb_build_object(
           'title', p.title, 'description', p.description,
           'image', jsonb_build_object('src', coalesce(p.image_path, ''), 'alt', p.image_alt),
           'link', jsonb_build_object('label', case when p.link_url is null then '' when p.link_label = '' then 'Learn More' else p.link_label end,
                                      'href', coalesce(p.link_url, ''), 'ariaLabel', ''),
           'placements', '["home"]'::jsonb, 'startsAt', '', 'endsAt', '', 'sortOrder', p.sort_order) end
  from public.promotion_drafts d
  left join public.promotions_published p on p.id = d.id;

  -- MVP uploads become media-library items.
  insert into public.cms_media (path, mime_type, size_bytes, public_at)
  select o.name, o.metadata ->> 'mimetype', (o.metadata ->> 'size')::integer,
         case when exists (select 1 from storage.objects x where x.bucket_id = 'cms-public' and x.name = o.name) then now() end
  from storage.objects o
  where o.bucket_id = 'cms-drafts'
    and o.name ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.(jpg|png|webp|avif)$'
  on conflict (path) do nothing;
end;
$carry$;

insert into public.cms_drafts (kind, key, data)
select kind, key, draft from cms_seed
on conflict (kind, key) do nothing;

-- Published rows use the seed's own published values, never an existing draft.
insert into public.cms_published (kind, key, data, version)
select s.kind, s.key, s.published, case when d.data = s.published then d.version else 0 end
from cms_seed s
join public.cms_drafts d on d.kind = s.kind and d.key = s.key
where s.published is not null
on conflict (kind, key) do nothing;

insert into public.cms_revisions (kind, key, data, version)
select p.kind, p.key, p.data, p.version
from public.cms_published p
where not exists (select 1 from public.cms_revisions r where r.kind = p.kind and r.key = p.key);

drop table cms_seed;
`

writeFileSync(new URL('supabase/seed.sql', root), sql)
console.log(`supabase/seed.sql: ${docs.length} documents`)
